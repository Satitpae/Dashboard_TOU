import assert from 'node:assert/strict';
import {dailyTou,totalTou,isHoliday} from './tou.mjs';
const start=Date.UTC(2026,8,1);
const allRows=Array.from({length:193},(_,i)=>({index:i,ts:start+i*900000,date:new Date(start+i*900000).toISOString().slice(0,10),demand:1,energy:1000+i,zero:false}));
const dataset={name:'test',rows:allRows.slice(0,192),allRows};
allRows[36].demand=100;allRows[88].demand=200;allRows[96].demand=300;
let days=dailyTou(dataset,{firstDayQuarter:false});
assert.deepEqual(days[0].energy,[44,52,0,96]);
assert.deepEqual(days[0].demand,[300,200,0]);
assert.deepEqual(dailyTou(dataset,{firstDayQuarter:false,boundaries:'strict'})[0].demand,[200,100,0]);
assert.equal(dailyTou(dataset)[0].energy[3],95);
const holiday=dailyTou(dataset,{firstDayQuarter:false,extra:new Set(['2026-09-01'])})[0];
assert.deepEqual(holiday.energy,[0,0,96,96]);assert.deepEqual(holiday.demand,[0,0,300]);
assert.equal(totalTou(days).demand[0],300);assert.equal(totalTou(days).energy[3],192);
allRows[8].energy=0;allRows[8].zero=true;
assert.equal(dailyTou(dataset,{firstDayQuarter:false})[0].energy[3],96);
allRows[36].energy=0;
assert.equal(dailyTou(dataset)[0].energy[1],null);
allRows[36].energy=1036;allRows[50].energy=10;
assert.equal(dailyTou(dataset)[0].energy[3],null);
assert.equal(isHoliday('2026-01-02'),false);assert.equal(isHoliday('2026-05-01'),true);
assert.equal(isHoliday('2026-09-05'),true);assert.equal(isHoliday('2026-09-07'),false);
const partialRows=Array.from({length:97},(_,i)=>({index:i,date:'2026-09-01',time:`${String(Math.floor(i/4)).padStart(2,'0')}:${String(i%4*15).padStart(2,'0')}`,demand:i<=40?2:0,energy:i<=40?1000+i:0,zero:i>40}));
const partial=dailyTou({name:'partial',rows:partialRows.slice(0,96),allRows:partialRows})[0];
assert.deepEqual(partial.energy,[35,4,0,39]);assert.equal(partial.endAt,'10:00');assert.equal(partial.partial,true);
console.log('PASS: TOU boundaries, Demand from raw column, holiday override, totals, gaps, reset, calendar.');
